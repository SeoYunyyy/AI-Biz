def map_topics_to_category(topics: list) -> str:
    # topics 배열에서 가장 잘 매칭되는 카테고리 반환 (없으면 '기타')
    if not topics:
        return '기타'
    topics_lower = [t.lower() for t in topics]
    scores = {}
    for category, keywords in CATEGORY_KEYWORDS.items():
        score = sum(
            1 for kw in keywords for t in topics_lower if kw in t or t in kw
        )
        if score > 0:
            scores[category] = score
    return max(scores, key=lambda k: scores[k]) if scores else '기타'
