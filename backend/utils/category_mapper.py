# 카테고리 달성에 필요한 저장 수
ITEM_THRESHOLD = 5


def map_topics_to_category(topics: list[str]) -> str | None:
    """
    AI가 추출한 topics[] → 가장 잘 매칭되는 카테고리 1개 반환

    매칭 방식:
    - 각 카테고리 키워드와 topic 간 부분 일치 점수를 합산
    - 가장 높은 점수의 카테고리를 선택
    - 매칭되는 카테고리 없으면 None 반환

    예시:
        >>> map_topics_to_category(["커피", "카페 추천", "브런치"])
        "카페/음료"
        >>> map_topics_to_category(["딥러닝", "AI 논문", "파이썬"])
        "IT/기술"
    """
    if not topics:
        return None

    category_scores: dict[str, int] = {}
    topics_lower = [t.lower() for t in topics]

    for category, keywords in CATEGORY_KEYWORDS.items():
        score = 0
        for keyword in keywords:
            for topic in topics_lower:
                # 키워드가 topic에 포함되거나, topic이 키워드에 포함되면 매칭
                if keyword in topic or topic in keyword:
                    score += 1
        if score > 0:
            category_scores[category] = score

    if not category_scores:
        return None

    return max(category_scores, key=lambda k: category_scores[k])
